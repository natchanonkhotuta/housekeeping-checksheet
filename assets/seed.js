function seedTaskDefs(areas){
  const out = [];
  areas.forEach(a=>{
    let tpl;
    if(a.code === 'BG') tpl = TASK_TEMPLATE.biogas;
    else if(a.code === 'HR' || a.code === 'SIT') tpl = TASK_TEMPLATE.office;
    else tpl = TASK_TEMPLATE.floor;
    tpl.forEach((t,i)=>{
      out.push({
        id: 'td_'+a.code.toLowerCase()+'_'+t[0].toLowerCase(),
        code: a.code+'-'+t[0],
        name: t[1], detail: t[2], areaId: a.id,
        freq: t[3], weekdays: t[4].slice(), monthDays: t[5].slice(), period: t[6],
        defaultStaffId: '', active: true, order: i+1
      });
    });
  });
  return out;
}

